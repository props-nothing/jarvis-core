//! Profile-owned speech choices. Provider adapters validate their own capabilities.

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};

/// Local synthesis compute/quality trade-off. Old voices retain Quality.
#[derive(Clone, Copy, Debug, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
pub enum VoiceQuality {
    /// Four diffusion steps.
    Fast,
    /// Six diffusion steps.
    Balanced,
    /// Ten diffusion steps.
    #[default]
    Quality,
}
impl VoiceQuality {
    /// Fixed engine budget; callers cannot request unbounded work.
    #[must_use]
    pub const fn steps(self) -> u8 {
        match self {
            Self::Fast => 4,
            Self::Balanced => 6,
            Self::Quality => 10,
        }
    }
}

/// Controls shared by speech adapters; absent values retain engine defaults.
#[derive(Clone, Debug, Default, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct VoiceSettings {
    /// Local generation quality; unsupported providers refuse it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub quality: Option<VoiceQuality>,
    /// Relative speaking rate.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub speed: Option<f64>,
    /// Consistency of the delivery.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stability: Option<f64>,
    /// Similarity to the source speaker.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub similarity_boost: Option<f64>,
    /// Style exaggeration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub style: Option<f64>,
    /// Additional speaker similarity processing.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub use_speaker_boost: Option<bool>,
}

/// A named voice, referencing an already configured provider, never a destination or key.
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct SavedVoice {
    /// Stable library identity.
    pub id: String,
    /// Owner-visible name.
    pub name: String,
    /// Configured provider identity.
    pub provider: String,
    /// Provider model identifier.
    pub model: String,
    /// Provider voice identifier.
    pub voice: String,
    /// Engine controls, individually optional.
    #[serde(default)]
    pub settings: VoiceSettings,
    /// Optional local design, validated and interpreted only by a capable adapter.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub blend: Option<crate::VoiceBlend>,
    /// Synthetic reference generated by a local description-capable engine.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub design: Option<crate::DesignedVoice>,
}

/// Channel overrides. Only channels with implemented speech delivery can be saved.
#[derive(Clone, Debug, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct VoiceChannels {
    /// Console override, or inherit the default.
    pub console: Option<String>,
}

/// Versioned profile voice library, replaced atomically with optimistic concurrency.
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct VoiceLibrary {
    /// Persisted format version (currently one).
    pub schema_version: u32,
    /// Compare-and-swap revision; zero means no saved library yet.
    pub revision: u64,
    /// At most 32 named voices.
    pub voices: Vec<SavedVoice>,
    /// Default voice, absent only for an empty library.
    pub default_voice: Option<String>,
    /// Ordered backup voices (up to seven).
    pub backups: Vec<String>,
    /// Surface-specific choices.
    #[serde(default)]
    pub channels: VoiceChannels,
}

pub(crate) fn identifier(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 64
        && value
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'-' | b'_'))
}

impl SavedVoice {
    /// Validate storage bounds, independently of provider capabilities.
    ///
    /// # Errors
    /// Returns a static, credential-free explanation for malformed fields.
    pub fn validate(&self) -> Result<(), &'static str> {
        if let Some(design) = &self.design {
            design.validate()?;
            if self.blend.is_some() {
                return Err("a voice cannot be both a preset blend and a generated design");
            }
        }
        if let Some(blend) = &self.blend {
            blend.validate()?;
        }
        if !identifier(&self.id) || !identifier(&self.provider) {
            return Err(
                "voice and provider IDs must be plain identifiers of at most 64 characters",
            );
        }
        if self.name.trim().is_empty()
            || self.name.chars().count() > 80
            || self.name.chars().any(char::is_control)
        {
            return Err("give the voice a name of 1–80 characters without control characters");
        }
        for value in [&self.model, &self.voice] {
            if value.is_empty() || value.len() > 128 || !value.bytes().all(|c| c.is_ascii_graphic())
            {
                return Err(
                    "voice and model must be nonempty identifiers of at most 128 characters",
                );
            }
        }
        for value in [
            self.settings.speed,
            self.settings.stability,
            self.settings.similarity_boost,
            self.settings.style,
        ]
        .into_iter()
        .flatten()
        {
            if !value.is_finite() {
                return Err("voice controls must be finite numbers");
            }
        }
        Ok(())
    }
}

impl VoiceLibrary {
    /// Validate references and bounds before storage or adapter construction.
    ///
    /// # Errors
    /// Refuses ambiguous identities, dangling routes or unsupported format versions.
    pub fn validate(&self) -> Result<(), &'static str> {
        if self.schema_version != 1 || self.voices.len() > 32 || self.backups.len() > 7 {
            return Err("voice library requires schema 1, at most 32 voices and seven backups");
        }
        let mut ids = BTreeSet::new();
        for voice in &self.voices {
            voice.validate()?;
            if !ids.insert(voice.id.as_str()) {
                return Err("each saved voice needs a unique ID");
            }
        }
        if self.voices.is_empty() != self.default_voice.is_none() {
            return Err("choose a default voice for a nonempty library");
        }
        for id in self
            .default_voice
            .iter()
            .chain(self.channels.console.iter())
            .chain(self.backups.iter())
        {
            if !ids.contains(id.as_str()) {
                return Err("a voice still used by a channel or backup cannot be removed");
            }
        }
        let mut backups = BTreeSet::new();
        for id in &self.backups {
            if !backups.insert(id) || self.default_voice.as_ref() == Some(id) {
                return Err("backup voices must be unique and different from the default");
            }
        }
        Ok(())
    }

    /// The primary voice for console speech.
    #[must_use]
    pub fn console_voice(&self) -> Option<&str> {
        self.channels
            .console
            .as_deref()
            .or(self.default_voice.as_deref())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_dangling_routes_unknown_controls_and_unimplemented_channels() {
        let mut library = VoiceLibrary {
            schema_version: 1,
            revision: 0,
            voices: vec![],
            default_voice: None,
            backups: vec![],
            channels: VoiceChannels::default(),
        };
        assert!(library.validate().is_ok());
        library.channels.console = Some("missing".into());
        assert!(library.validate().is_err());
        assert!(serde_json::from_str::<VoiceSettings>(r#"{"pitch":1}"#).is_err());
        assert!(serde_json::from_str::<VoiceChannels>(r#"{"telegram":"voice"}"#).is_err());
    }
}
